package com.digithon.hr.security;

import jakarta.persistence.EntityManagerFactory;
import org.hibernate.engine.spi.EntityEntry;
import org.hibernate.engine.spi.SessionFactoryImplementor;
import org.hibernate.event.service.spi.EventListenerRegistry;
import org.hibernate.event.spi.EventSource;
import org.hibernate.event.spi.EventType;
import org.hibernate.event.spi.PostInsertEvent;
import org.hibernate.event.spi.PostInsertEventListener;
import org.hibernate.event.spi.PostLoadEvent;
import org.hibernate.event.spi.PostLoadEventListener;
import org.hibernate.event.spi.PostUpdateEvent;
import org.hibernate.event.spi.PostUpdateEventListener;
import org.hibernate.persister.entity.AbstractEntityPersister;
import org.hibernate.persister.entity.EntityPersister;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.InitializingBean;
import org.springframework.beans.factory.ObjectProvider;
import org.springframework.stereotype.Component;

import java.sql.PreparedStatement;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.concurrent.ConcurrentHashMap;

/**
 * Generated by PI Co-Pilot. Keeps the read-only "_enc" fields of the entities current:
 * <ul>
 *   <li>after every insert or update, writes the encrypted values to the "_enc" columns in the same
 *       transaction, whether encrypted read is on or off, so both copies always match;</li>
 *   <li>after a load, while PiEncryptionFlags reports encrypted read on, replaces the entity's PI fields
 *       with the decrypted "_enc" values. While it is off, reads come from the plain columns as before.</li>
 * </ul>
 */
@Component
public class PiEncryptionListener implements PostInsertEventListener, PostUpdateEventListener,
        PostLoadEventListener, InitializingBean {

    private static final Logger log = LoggerFactory.getLogger(PiEncryptionListener.class);

    private final EntityManagerFactory entityManagerFactory;
    private final ObjectProvider<PiFieldCipher> cipher;

    public PiEncryptionListener(EntityManagerFactory entityManagerFactory, ObjectProvider<PiFieldCipher> cipher) {
        this.entityManagerFactory = entityManagerFactory;
        this.cipher = cipher;
    }

    @Override
    public void afterPropertiesSet() {
        EventListenerRegistry registry = entityManagerFactory.unwrap(SessionFactoryImplementor.class)
            .getServiceRegistry().getService(EventListenerRegistry.class);
        registry.appendListeners(EventType.POST_INSERT, this);
        registry.appendListeners(EventType.POST_UPDATE, this);
        registry.appendListeners(EventType.POST_LOAD, this);
    }

    @Override
    public void onPostInsert(PostInsertEvent event) {
        write(event.getPersister(), event.getId(), event.getState(), event.getSession());
    }

    @Override
    public void onPostUpdate(PostUpdateEvent event) {
        write(event.getPersister(), event.getId(), event.getState(), event.getSession());
    }

    @Override
    public boolean requiresPostCommitHandling(EntityPersister persister) {
        return false;
    }

    /** A plain property and its read-only "_enc" twin on the same entity. */
    private record Twin(int plain, int encrypted, String column) {}

    private final Map<String, List<Twin>> twins = new ConcurrentHashMap<>();

    /**
     * Twins of an entity, found from its mapping: a property whose column is "<c>_enc" pairs with the
     * property mapped to column "<c>". No list of fields is kept; the entity's own fields define them.
     */
    private List<Twin> twins(EntityPersister persister) {
        return twins.computeIfAbsent(persister.getEntityName(), name -> {
            if (!(persister instanceof AbstractEntityPersister)) return List.of();
            AbstractEntityPersister p = (AbstractEntityPersister) persister;
            String[] names = persister.getPropertyNames();
            Map<String, Integer> byColumn = new HashMap<>();
            for (int i = 0; i < names.length; i++) {
                String[] columns = p.getPropertyColumnNames(i);
                if (columns.length == 1) byColumn.put(columns[0].toLowerCase(Locale.ROOT), i);
            }
            List<Twin> found = new ArrayList<>();
            byColumn.forEach((column, index) -> {
                if (!column.endsWith("_enc")) return;
                Integer plain = byColumn.get(column.substring(0, column.length() - 4));
                if (plain != null) found.add(new Twin(plain, index, column));
            });
            return List.copyOf(found);
        });
    }

    private volatile boolean keyWarned;

    private void write(EntityPersister persister, Object id, Object[] state, EventSource session) {
        List<Twin> fields = twins(persister);
        if (fields.isEmpty()) return;
        AbstractEntityPersister p = (AbstractEntityPersister) persister;
        List<String> sets = new ArrayList<>();
        List<String> values = new ArrayList<>();
        try {
            for (Twin twin : fields) {
                Object value = state[twin.plain()];
                sets.add(twin.column() + " = ?");
                values.add(value == null ? null : cipher.getObject().encrypt(value.toString()));
            }
        } catch (IllegalStateException e) {
            // Key not configured yet: with encrypted read off the save still goes through on the plain
            // columns, as before. With it on, the save must fail rather than leave a stale copy.
            if (PiEncryptionFlags.encryptedRead()) throw e;
            if (!keyWarned) {
                keyWarned = true;
                log.warn("Encrypted copies are not being written: {}", e.getMessage());
            }
            return;
        }
        String sql = "UPDATE " + p.getTableName() + " SET " + String.join(", ", sets)
            + " WHERE " + p.getIdentifierColumnNames()[0] + " = ?";
        session.doWork(connection -> {
            try (PreparedStatement st = connection.prepareStatement(sql)) {
                for (int i = 0; i < values.size(); i++) st.setString(i + 1, values.get(i));
                st.setObject(values.size() + 1, id);
                st.executeUpdate();
            }
        });
    }

    @Override
    public void onPostLoad(PostLoadEvent event) {
        if (!PiEncryptionFlags.encryptedRead()) return;
        EntityPersister persister = event.getPersister();
        List<Twin> fields = twins(persister);
        if (fields.isEmpty()) return;
        Object entity = event.getEntity();
        EntityEntry entry = event.getSession().getPersistenceContextInternal().getEntry(entity);
        Object[] loaded = entry == null ? null : entry.getLoadedState();
        String[] names = persister.getPropertyNames();
        for (Twin twin : fields) {
            // The read-only twin was loaded with the entity, so no extra query is needed
            Object encrypted = persister.getValue(entity, twin.encrypted());
            if (encrypted == null) continue; // not synced yet: keep the plain value
            String value;
            try {
                value = cipher.getObject().decrypt(encrypted.toString());
            } catch (RuntimeException e) {
                log.warn("Could not decrypt {}.{}; using the plain value", persister.getEntityName(), names[twin.plain()], e);
                continue;
            }
            persister.setValue(entity, twin.plain(), value);
            // Also the loaded snapshot, so Hibernate does not see the entity as modified
            if (loaded != null) loaded[twin.plain()] = value;
        }
    }
}
